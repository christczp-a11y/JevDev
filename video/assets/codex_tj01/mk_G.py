def abs_refs(n):
    out = []
    for r in REFS[n]:
        p = A / r
        if not p.exists():
            p = HERE / r
        out.append(str(p).replace("\\", "/"))
    return out


def main():
    cmd, names = sys.argv[1], sys.argv[2:]
    if cmd == "write":
        for n in names or list(P):
            (HERE / f"{n}.txt").write_text(P[n], encoding="utf-8")
            print("wrote", n)
    elif cmd == "cmds":
        for n in names:
            (HERE / f"{n}.txt").write_text(P[n], encoding="utf-8")
            refs = " ".join(f'"{r}"' for r in abs_refs(n))
            print(f'bash video/codex_gen.sh "{str(HERE).replace(chr(92), "/")}" {n} {refs} &')
        print("wait")
    else:
        raise SystemExit(__doc__)


