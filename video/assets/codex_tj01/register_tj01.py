def size_of(rel):
    im = Image.open(ASSETS / rel)
    return f"{im.width}×{im.height}"


def owner_of(stem):
    pre = stem.split("_")[0]
    if pre in PEOPLE:
        return f"{PEOPLE[pre][0].split('（')[0]} `{pre}_`"
    return pre


