def size_of(rel):
    return Image.open(ASSETS / rel).size


def limit(rel):
    w, h = size_of(rel)
    return f"（原图 {w}×{h}，屏幕显示不超过 {round(w * 1.3)}×{round(h * 1.3)}）"


def main():
    md = REG.read_text(encoding="utf-8")
    lines = md.split("\n")
    registered = set(re.findall(r"^\| `((?:chars|props|rig|sets|brand)/[^`]+\.png)`", md, re.M))
    rows = []
    for stem, (face, note, scope) in PROPS.items():
        rel = f"props/{stem}.png"
        if not (ASSETS / rel).exists() or rel in registered:
            continue
        w, h = size_of(rel)
        rows.append(f"| `{rel}` | 道具 | {face} | {w}×{h} | 无 | 定稿 | {note} {limit(rel)} | {scope} |")
    if rows:
        j = next(k for k, l in enumerate(lines) if l.startswith("### 2.3"))
        k = j - 1
        while k > 0 and not lines[k].startswith("|"):
            k -= 1
        lines[k + 1:k + 1] = rows
    md2 = "\n".join(lines)
    old = next((l for l in md2.split("\n") if l.startswith("| `video/assets/codex_tj03/`")), None)
    if old and "wuh_pose_c" not in old:
        new = old.rstrip(" |") + (
            "；**第 5 步（画面素材）**：新画的表和整幅图（`wuh_pose_c`〔C1、C2〕、`card_sanmiao` / `card_xiajie` / `card_shangzhou`〔P1–P3〕、`props_a`〔P4、P5、P7；里面的小青山太扁，换成 `mini_mountains`〕、`mini_mountains`〔P6 第二版〕、`icons_boat`〔P8、P9；`icons_boat_v1` 是船画小了的旧版〕、"
            "`bubble_wall_nap` / `bubble_knight_a` / `bubble_knight_bc` / `bubble_knight_d`〔B1–B4〕）、`split_tj03.py`（新图只抠外面的绿底：草地、山是绿的）、`make_scale_heart.py`（`scale_heart_a/b`）、`make_oars_fg.py`（`rower_oars_fg`）、"
            "`register_tj03_5.py`（登记道具）、`board_tj03_5.py`（新素材总览 `video/out/tj03/assets_new.png`，不进 git） |")
        md2 = md2.replace(old, new)
    REG.write_text(md2, encoding="utf-8")
    print(f"登记：道具 {len(rows)} 行")


if __name__ == "__main__":
    main()
