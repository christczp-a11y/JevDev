def size_of(rel):
    im = Image.open(ASSETS / rel)
    return im.size


def limit(rel):
    w, h = size_of(rel)
    return f"（原图 {w}×{h}，屏幕显示不超过 {round(w * 1.3)}×{round(h * 1.3)}）"


def main():
    md = REG.read_text(encoding="utf-8")
    lines = md.split("\n")
    registered = set(re.findall(r"^\| `((?:chars|props|rig|sets|brand)/[^`]+\.png)`", md, re.M))
    new_chars, new_props, new_sets = [], [], []
    for stem, (owner, face, note, scope) in CHARS.items():
        rel = f"chars/{stem}.png"
        if not (ASSETS / rel).exists() or rel in registered:
            continue
        w, h = size_of(rel)
        new_chars.append(f"| `{rel}` | {owner} | {face} | {w}×{h} | {BAKED.get(stem, '无')} | 定稿 | {note} {limit(rel)} | {scope} |")
    for stem, (face, note, scope) in PROPS.items():
        rel = f"props/{stem}.png"
        if not (ASSETS / rel).exists() or rel in registered:
            continue
        w, h = size_of(rel)
        new_props.append(f"| `{rel}` | 道具 | {face} | {w}×{h} | 无 | 定稿 | {note} {limit(rel)} | {scope} |")
    for stem, (owner, face, note, scope) in SETS.items():
        rel = f"sets/{stem}.png"
        if not (ASSETS / rel).exists() or rel in registered:
            continue
        w, h = size_of(rel)
        new_sets.append(f"| `{rel}` | {owner} | {face} | {w}×{h} | 无 | 定稿 | {note} {limit(rel)} | {scope} |")
    new_people = []
    for pre, (nm, code, look) in PEOPLE5.items():
        if f"`{pre}_`" in md or not any((ASSETS / "chars").glob(f"{pre}_*.png")):
            continue
        new_people.append(f"| {nm} | {code} | tj02 | {look} | {M.px(pre)} | 定稿 |")

    def insert_before(prefix, rows):
        if not rows:
            return
        j = next(k for k, l in enumerate(lines) if l.startswith(prefix))
        k = j - 1
        while k > 0 and not lines[k].startswith("|"):
            k -= 1
        lines[k + 1:k + 1] = rows

    insert_before("### 2.2", new_chars)
    insert_before("### 2.3", new_props)
    insert_before("### 2.5", new_sets)
    insert_before("tj01 的新角色（智、赵、韩、魏各家的人物）画完以后", new_people)
    md2 = "\n".join(lines)
    old_row = next((l for l in md2.split("\n") if l.startswith("| `video/assets/codex_tj02/`")), None)
    if old_row and "split_tj02_5.py" not in old_row:
        new_row = old_row.rstrip(" |") + (
            "；**第 5 步（画面素材，本表）**：新画的素材表和整幅图（`set_sky_rain`、`set_hut`、`set_mud`、`wwh_rain_a/b/c`、`yr_hi_a/b/c`、`yr_l_a/b`、`wdc_run`、`wdc_pant`、`sgm_hi_magnify`、`wuh_point`、`hands_remote`、"
            "`paperman`、`flags_pigeon`、`frogs`、`magnet`、`scale_a/b`、`magnifier`、`boat`、`bubble_*`；`*_v1.png` 是被重画换掉的旧版）、`run_tj02_5.sh`（并行调 Codex）、`split_tj02_5.py`（拆图、对位、拆船的前后层）、"
            "`register_tj02_5.py`（登记）、`make_composites_tj02.py`（拼 `screen_rain_ride`、`bubble_yr_wait`）、`board_tj02_5.py`（新素材总览 `video/out/tj02/assets_new.png`） |")
        md2 = md2.replace(old_row, new_row)
    REG.write_text(md2, encoding="utf-8")
    print(f"登记：人物 {len(new_people)} 行，姿势图 {len(new_chars)}，道具 {len(new_props)}，布景 {len(new_sets)}")


if __name__ == "__main__":
    main()
